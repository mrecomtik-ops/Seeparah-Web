-- Gutenberg fast-track queue. RLS-restricted and service-role only.
-- Only verified, low-risk original-language classics are seeded here.
-- Newly fetched content must pass source, rights and reader gates before publish.
create table if not exists public.gutenberg_import_jobs (
  id bigint generated by default as identity primary key,
  gutenberg_id integer not null unique check (gutenberg_id between 1 and 9999999),
  original_publication_year integer not null
    check (original_publication_year between 1400 and 2026),
  status text not null default 'queued'
    check (status in ('queued','processing','published','in_review','skipped','failed')),
  book_id uuid references public.books(id) on delete set null,
  attempts smallint not null default 0,
  last_error text,
  source_sha256 text,
  metadata jsonb,
  enqueued_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.gutenberg_import_jobs enable row level security;
revoke all on public.gutenberg_import_jobs from public,anon,authenticated;
revoke all on sequence public.gutenberg_import_jobs_id_seq from public,anon,authenticated;
grant select,insert,update on public.gutenberg_import_jobs to service_role;
grant usage,select on sequence public.gutenberg_import_jobs_id_seq to service_role;
create index if not exists gutenberg_import_jobs_pending
  on public.gutenberg_import_jobs(status,enqueued_at,id);

