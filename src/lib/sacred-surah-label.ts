/** Give readers a sourced name alongside the already verified surah number. */
export function sourcedSurahLabel(label: string): string {
  const found = /^Surah\s+(\d{1,3})$/i.exec(label.trim());
  if (!found) return label;
  const number = Number(found[1]);
  const name = QURAN_SURAH_ARABIC_NAMES[number - 1];
  return name ? `Surah ${number} · ${name}` : label;
}
